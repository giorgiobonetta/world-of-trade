import fs from 'fs';
const read = f => fs.readFileSync(new URL('../'+f, import.meta.url), 'utf8');
let pass=0, fail=0;
const t=(n,v)=>{if(v){pass++;console.log('  ✓ '+n)}else{fail++;console.log('  ✗ '+n)}};
const home=read('index.html'), landing=read('landing.html'), access=read('access.html'), login=read('login.html'), register=read('register.html');
t('root file is the landing, not an app redirect', /class="site-nav"/.test(home) && !/location\.(?:href|replace)\s*=?.*learn/.test(home));
t('landing does not expose separate login/register buttons', !/href="login\.html"[^>]*>Log in</.test(home) && !/href="register\.html"[^>]*>Create account</.test(home));
t('Start trading routes to unified access page', /href="access\.html"[^>]*>Start trading</.test(home));
t('landing alias keeps the same unified access route', /href="access\.html"[^>]*>Start trading</.test(landing));
t('unified access page offers both login and registration', /Log in/.test(access) && /Create account/.test(access) && /access-page\.js/.test(access));
t('login page uses the public visual shell', /site\.css/.test(login) && /auth\.css/.test(login) && /logo-crest-220/.test(login));
t('registration page uses the public visual shell', /site\.css/.test(register) && /auth\.css/.test(register) && /logo-crest-220/.test(register));
t('login loads existing Supabase public config and auth controller', /supabase-config\.js/.test(login) && /auth-page\.js/.test(login));
t('registration loads existing Supabase public config and auth controller', /supabase-config\.js/.test(register) && /auth-page\.js/.test(register));
t('login and registration are noindex', /noindex,nofollow/.test(login) && /noindex,nofollow/.test(register));
const game=read('learn.html');
t('game itself is noindex', /name="robots" content="noindex,follow"/.test(game));
t('game canonical points to public landing', /canonical" href="https:\/\/www\.worldoftrade\.app\/"/.test(game));
const sitemap=read('sitemap.xml');
t('sitemap contains public landing but not game/auth pages', /worldoftrade\.app\/<\/loc>/.test(sitemap) && !/\/learn</.test(sitemap) && !/\/login</.test(sitemap) && !/\/register</.test(sitemap));
const robots=read('robots.txt');
t('robots keeps game and auth pages out of search', /Disallow: \/learn/.test(robots) && /Disallow: \/login/.test(robots) && /Disallow: \/register/.test(robots));
const js=read('auth-page.js');
t('auth shares the same session key as the game', /wot-cloud-session/.test(js));
t('successful authentication opens the game', /location\.replace\('learn\.html'\)/.test(js));
t('registration checks matching passwords', /passwords do not match/.test(js));
console.log(`\nPublic auth: ${pass} passed, ${fail} failed`); process.exitCode=fail?1:0;
